describe('R80 M3: the send class and the permanent refusal', () => {
	it('2xx is registered; a 4xx is refused (never retried); a 5xx or no answer is retry (backoff)', () => {
		expect(classifyRegisterSend({ ok: true })).toBe('registered')
		expect(classifyRegisterSend({ ok: false, reason: 'refused_4xx' })).toBe('refused')
		expect(classifyRegisterSend({ ok: false, reason: 'server_5xx' })).toBe('retry')
		expect(classifyRegisterSend({ ok: false, reason: 'network' })).toBe('retry')
	})

	it('a busy lock is busy, never a failure: the send is not made and no refusal is recorded', async () => {
		const locks: LockManagerLike = { request: async (_n, _o, cb) => cb(null) }
		let sent = 0
		const r = await registerUnderFirstOpenLock('0x' + '6'.repeat(40), { lookup: async () => ({ status: 'no_record' }), send: async () => (sent++, 'registered'), locks })
		expect(r).toBe('busy')
		expect(sent).toBe(0)
	})

	it('a refusal is kept per wallet on this device, so the gate stays closed for it', () => {
		const store = new Map<string, string>()
		const fake = { getItem: (k: string) => store.get(k) ?? null, setItem: (k: string, v: string) => void store.set(k, v) }
		expect(isFirstOpenRefused('0x' + '7'.repeat(40), fake)).toBe(false)
		markFirstOpenRefused('0x' + '7'.repeat(40), fake)
		expect(isFirstOpenRefused('0x' + '7'.repeat(40), fake)).toBe(true)
		expect(isFirstOpenRefused('0x' + '8'.repeat(40), fake)).toBe(false)
	})
})

describe('R81 M2: an unregistered key this device generated is pending, not an old identity', () => {
	it('a chat key with origin auto, no record on the chain, no pending copy: resumed (the register step continues it), not kept as an old identity', () => {
		const d = firstOpenDecisionNow({ read: EMPTY, publicArmored: '', pending: false, localChatKeyComplete: true, localChatKeyAutoGenerated: isAutoGeneratedChatKey({ origin: 'auto' }) })
		expect(d).toBe('resume_pending')
		expect(firstOpenRegisterAllowed(d)).toBe(true)
	})

	it('a complete chat key without the auto origin is still an old identity (kept)', () => {
		const d = firstOpenDecisionNow({ read: EMPTY, publicArmored: '', pending: false, localChatKeyComplete: true, localChatKeyAutoGenerated: isAutoGeneratedChatKey({}) })
		expect(d).toBe('keep_protection')
	})

	it('the origin marker is read only from an auto origin', () => {
		expect(isAutoGeneratedChatKey({ origin: 'auto' })).toBe(true)
		expect(isAutoGeneratedChatKey({ origin: 'restored' })).toBe(false)
		expect(isAutoGeneratedChatKey(undefined)).toBe(false)
	})
})

