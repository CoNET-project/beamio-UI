/**
 * The first-open wiring policy: the decision comes from the existing restore judgement; the pending key is its own
 * field; the registration is single per wallet and re-reads the chain first. SYNTHETIC values only.
 */
import { clearFirstOpenRefused, retryFirstOpenAfterRefusal, FIRST_OPEN_RULE_VERSION, isAutoGeneratedChatKey, classifyRegisterSend, firstOpenDecisionNow, firstOpenRegisterAllowed, isFirstOpenRefused, markFirstOpenRefused, readPendingChatKey, registerUnderFirstOpenLock, writePendingChatKey, chainFromOwnRead } from './firstOpenPolicy'
import type { OwnChainRead } from './chatOwnRoutePlan'
import type { LockManagerLike } from './autoFirstOpen'

const ARMOR = '-----BEGIN PGP PUBLIC KEY BLOCK-----\nSYNTH\n-----END PGP PUBLIC KEY BLOCK-----'
const EMPTY: OwnChainRead = { status: 'empty' }

describe('the decision from the own-chain read', () => {
	it('a browser account with no record and no backup: the first identity is confirmed, so the registration is allowed', () => {
		const d = firstOpenDecisionNow({ read: EMPTY, publicArmored: '', pending: false, localChatKeyComplete: false, localChatKeyAutoGenerated: false })
		expect(d).toBe('generate_and_register')
		expect(firstOpenRegisterAllowed(d)).toBe(true)
	})

	it('a saved key not yet registered is continued on restart (resume), never regenerated', () => {
		const d = firstOpenDecisionNow({ read: EMPTY, publicArmored: '', pending: true, localChatKeyComplete: false, localChatKeyAutoGenerated: false })
		expect(d).toBe('resume_pending')
		expect(firstOpenRegisterAllowed(d)).toBe(true)
	})

	it('R80 M4: a record whose public armor cannot be read is unknown on the decision path: it waits, nothing is generated', () => {
		const read: OwnChainRead = { status: 'ok', userKeyID: '0x1', routeKeyID: '0x2', routeArmor: ARMOR, privateBlob: 'ok' }
		expect(chainFromOwnRead(read, 'not-an-armor')).toBe('unknown')
		const d = firstOpenDecisionNow({ read, publicArmored: 'not-an-armor', pending: false, localChatKeyComplete: false, localChatKeyAutoGenerated: false })
		expect(d).toBe('wait_unknown')
		expect(firstOpenRegisterAllowed(d)).toBe(false)
	})

	it('R80 M2: an existing complete chat key the flow did not create is an old identity: it is never replaced', () => {
		const d = firstOpenDecisionNow({ read: EMPTY, publicArmored: '', pending: false, localChatKeyComplete: true, localChatKeyAutoGenerated: false })
		expect(d).toBe('keep_protection')
		expect(firstOpenRegisterAllowed(d)).toBe(false)
	})

	it('R80 M2: a saved pending key is this flow\'s own even when a chat key is present: it is continued, not kept as an old identity', () => {
		const d = firstOpenDecisionNow({ read: EMPTY, publicArmored: '', pending: true, localChatKeyComplete: true, localChatKeyAutoGenerated: false })
		expect(d).toBe('resume_pending')
	})

	it('an existing route stays on the original path: no first open', () => {
		const d = firstOpenDecisionNow({ read: { status: 'ok', userKeyID: '0x1', routeKeyID: '0x2', routeArmor: ARMOR, privateBlob: 'ok' }, publicArmored: ARMOR, pending: false, localChatKeyComplete: false, localChatKeyAutoGenerated: false })
		expect(d).toBe('use_record')
		expect(firstOpenRegisterAllowed(d)).toBe(false)
	})

	it('a restore failure (a backup that cannot be read) keeps the protection: nothing is generated', () => {
		const d = firstOpenDecisionNow({ read: { status: 'ok', userKeyID: '0x1', routeKeyID: '0x2', routeArmor: ARMOR, privateBlob: 'missing' }, publicArmored: ARMOR, pending: false, localChatKeyComplete: false, localChatKeyAutoGenerated: false })
		expect(firstOpenRegisterAllowed(d)).toBe(false)
	})

	it('an unknown read (an RPC error) waits: nothing is generated', () => {
		const d = firstOpenDecisionNow({ read: { status: 'error', reason: 'timeout' }, publicArmored: '', pending: false, localChatKeyComplete: false, localChatKeyAutoGenerated: false })
		expect(d).toBe('wait_unknown')
		expect(firstOpenRegisterAllowed(d)).toBe(false)
		expect(chainFromOwnRead({ status: 'error', reason: 'timeout' })).toBe('unknown')
	})
})

describe('the pending key is its own field (never the chat key)', () => {
	it('a pending key is written and read back; a profile without one reads null', () => {
		const profile: Record<string, unknown> = { keyID: '0xabc', chatManager: undefined }
		expect(readPendingChatKey(profile)).toBeNull()
		writePendingChatKey(profile, { keyID: 'K1', privateKey: 'P', publicKey: 'U' })
		expect(readPendingChatKey(profile)).toEqual({ keyID: 'K1', privateKey: 'P', publicKey: 'U' })
		expect(profile.chatManager).toBeUndefined()
		writePendingChatKey(profile, null)
		expect(readPendingChatKey(profile)).toBeNull()
	})

	it('an incomplete pending record reads as no pending key', () => {
		expect(readPendingChatKey({ pendingChatFirstOpen: { keyID: 'K1', privateKey: '', publicKey: 'U' } })).toBeNull()
	})
})

describe('registration under the wallet lock with a fresh chain read', () => {
	const EOA = '0x' + '5'.repeat(40)

	it('a definite absent answer on the fresh read: the registration is sent once', async () => {
		let sent = 0
		const ok = await registerUnderFirstOpenLock(EOA, { lookup: async () => ({ status: 'no_record' }), send: async () => (sent++, 'registered') })
		expect(ok).toBe('registered')
		expect(sent).toBe(1)
	})

	it('a record that appeared before the send: nothing is sent', async () => {
		let sent = 0
		const ok = await registerUnderFirstOpenLock(EOA, {
			lookup: async () => ({ status: 'ok', publicArmored: ARMOR, routersArmoreds: ARMOR }),
			send: async () => (sent++, 'registered'),
		})
		expect(ok).toBe('stopped')
		expect(sent).toBe(0)
	})

	it('a failed fresh read never counts as absent: nothing is sent', async () => {
		let sent = 0
		const ok = await registerUnderFirstOpenLock(EOA, { lookup: async () => ({ status: 'network_error', reason: 'rpc' }), send: async () => (sent++, 'registered') })
		expect(ok).toBe('stopped')
		expect(sent).toBe(0)
	})

	it('two tabs at once: one registration', async () => {
		const held = new Set<string>()
		const locks: LockManagerLike = {
			request: async (name, _o, cb) => {
				if (held.has(name)) return cb(null)
				held.add(name)
				try {
					return await cb({})
				} finally {
					held.delete(name)
				}
			},
		}
		let sent = 0
		const lookup = async () => {
			await new Promise((r) => setTimeout(r, 5))
			return { status: 'no_record' as const }
		}
		const send = async () => (sent++, 'registered' as const)
		await Promise.all([registerUnderFirstOpenLock(EOA, { lookup, send, locks }), registerUnderFirstOpenLock(EOA, { lookup, send, locks })])
		expect(sent).toBe(1)
	})
})

