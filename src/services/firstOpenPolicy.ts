/**
 * The policy that wires the automatic first open into the chat (browser path; the shell keeps its native state).
 * Pure helpers: the decision from the own-chain read through the existing restore judgement, the pending key in its own profile field
 * (pendingChatFirstOpen, never chatManager.pgpKey), and the registration under the per-wallet lock with a fresh chain read.
 */
import { autoFirstOpenDecision, chainBackupFromRead, chainReadFromLookup, classifyLocalIdentity, wellFormedPublicArmor, withFirstOpenLock, type AutoFirstOpenDecision, type ChainBackupRead, type ChainPgpRead, type LockManagerLike } from './autoFirstOpen'
import { classifyOwnPgp } from './pgpRestore'
import type { OwnChainRead } from './chatOwnRoutePlan'
import type { RecipientLookup } from './recipientRecord'

/**
 * R81 M1 (option: pause). The page's automatic first open generates no new key while this is true: the generation and the save happen
 * outside the per-wallet lock on the page side, so two tabs could store different pending keys. The whole flow (decision, generation,
 * save, re-read, registration, clear) is in the SDK under one lock (vendor/conet-chat-sdk firstOpen.ts runFirstOpen); the page takes it
 * over in the next step. A saved key that is already on the device is still continued (resume), never regenerated.
 */

export type PendingChatKey = { keyID: string; privateKey: string; publicKey: string }

/** The key this flow saved and has not registered. Its own field: a restart reads it, never judges it as an old identity. */
export function readPendingChatKey(profile: unknown): PendingChatKey | null {
	const k = (profile as { pendingChatFirstOpen?: Partial<PendingChatKey> | null } | null | undefined)?.pendingChatFirstOpen
	if (!k || typeof k.keyID !== 'string' || typeof k.privateKey !== 'string' || typeof k.publicKey !== 'string') return null
	if (!k.keyID || !k.privateKey || !k.publicKey) return null
	return { keyID: k.keyID, privateKey: k.privateKey, publicKey: k.publicKey }
}

export function writePendingChatKey(profile: unknown, key: PendingChatKey | null): void {
	;(profile as { pendingChatFirstOpen?: PendingChatKey | null }).pendingChatFirstOpen = key
}

/**
 * The own chain record in three states. A record whose public armor cannot be read (missing, malformed) is unknown, never a record: the
 * armor is checked on the decision path itself, not only on the locked re-read (R80 M4).
 */
/** R81 M2: a chat key this device generated in the first open flow is pending, never an old identity (its origin is 'auto'). */
export function isAutoGeneratedChatKey(key: unknown): boolean {
	return (key as { origin?: unknown } | null | undefined)?.origin === 'auto'
}

export function chainFromOwnRead(read: OwnChainRead, publicArmored: string = ''): ChainPgpRead {
	if (read.status === 'empty') return 'absent'
	// both armors must be readable: the public key and the route (R81 M4 completion; the lookup requires both as well)
	if (read.status === 'ok') return wellFormedPublicArmor(publicArmored) && wellFormedPublicArmor(read.routeArmor) ? 'record' : 'unknown'
	return 'unknown'
}

export function backupFromOwnRead(read: OwnChainRead): ChainBackupRead {
	return read.status === 'ok' ? chainBackupFromRead(read.privateBlob) : 'absent'
}

/**
 * The decision of this run from the own-chain read. The restore judgement is the existing classifyOwnPgp (no second judgement). The local
 * identity comes from classifyLocalIdentity (R80 M2): an existing complete chat key that the flow did not create is an old identity and is
 * never replaced; a saved pending key is this flow's own and is continued.
 */
export function firstOpenDecisionNow(input: {
	read: OwnChainRead
	publicArmored: string
	pending: boolean
	localChatKeyComplete: boolean
	localChatKeyAutoGenerated: boolean
}): AutoFirstOpenDecision {
	const restore = classifyOwnPgp({ read: input.read, localKeyID: '', hasLocalKey: false })
	const local = classifyLocalIdentity({
		chatKeyComplete: input.localChatKeyComplete,
		chatKeyAutoGenerated: input.localChatKeyAutoGenerated,
		pendingKeyPresent: input.pending,
	})
	return autoFirstOpenDecision({
		restore,
		chain: chainFromOwnRead(input.read, input.publicArmored),
		chainBackup: backupFromOwnRead(input.read),
		localOldIdentity: local.localOldIdentity,
		localPendingOwn: local.localPendingOwn,
	})
}

/** Only a confirmed first identity may register: a new key to generate, or the saved key to continue. */
export function firstOpenRegisterAllowed(decision: AutoFirstOpenDecision): boolean {
	return decision === 'generate_and_register' || decision === 'resume_pending'
}

/** The result of one send: a confirmed registration, a permanent refusal (4xx), or a retry with the backoff (5xx, network, others). */
export type RegisterSendClass = 'registered' | 'refused' | 'retry'
/** The result of the locked flow: the send's class, or busy (another tab holds the wallet; not a failure), or stopped (a record or unknown). */
export type FirstOpenLockResult = RegisterSendClass | 'busy' | 'stopped'

/** Maps one registration outcome to the class the first open acts on (R80 M3). */
export function classifyRegisterSend(outcome: { ok: boolean; reason?: string }): RegisterSendClass {
	if (outcome.ok) return 'registered'
	if (outcome.reason === 'refused_4xx') return 'refused'
	return 'retry'
}

/**
 * One registration under the wallet's first-open lock (tabs included). The chain is read again first: only a definite absent answer sends;
 * a record or an unknown answer stops. A busy lock is returned as busy, never as a failure.
 */
export async function registerUnderFirstOpenLock(
	eoa: string,
	deps: { lookup: () => Promise<RecipientLookup>; send: () => Promise<RegisterSendClass>; locks?: LockManagerLike },
): Promise<FirstOpenLockResult> {
	const r = await withFirstOpenLock(
		eoa,
		async (): Promise<FirstOpenLockResult> => {
			const again = chainReadFromLookup(await deps.lookup().catch((): RecipientLookup => ({ status: 'network_error', reason: 'read' })))
			if (again !== 'absent') return 'stopped'
			return deps.send()
		},
		deps.locks,
	)
	return r
}

/**
 * A permanent refusal of this wallet (a 4xx), kept on this device so the automatic first open does not send again. Clear paths (R81 item 4):
 * (1) a new build with a new first-open rule version (the marker carries the version, a different version reads as no refusal);
 * (2) the chain shows the record (the refusal is no longer needed: clearFirstOpenRefused is called after a verified registration);
 * (3) an explicit retry by the user (retryFirstOpenAfterRefusal; no UI yet, the function is ready for it).
 */
export const FIRST_OPEN_RULE_VERSION = '0.53.22'
const REFUSED_PREFIX = 'beamio.firstOpenRefused.v1:'
export type RefusedStore = Pick<Storage, 'getItem' | 'setItem'>
function refusedStoreOrNull(): RefusedStore | null {
	try {
		return typeof localStorage === 'undefined' ? null : localStorage
	} catch {
		return null
	}
}
const refusedValue = (): string => `4xx:${FIRST_OPEN_RULE_VERSION}`
export function markFirstOpenRefused(eoa: string, store: RefusedStore | null = refusedStoreOrNull()): void {
	try {
		store?.setItem(REFUSED_PREFIX + eoa.toLowerCase(), refusedValue())
	} catch {
		/* not persisted: this session still stops at the gate */
	}
}
export function isFirstOpenRefused(eoa: string, store: RefusedStore | null = refusedStoreOrNull()): boolean {
	try {
		return store?.getItem(REFUSED_PREFIX + eoa.toLowerCase()) === refusedValue()
	} catch {
		return false
	}
}
export function clearFirstOpenRefused(eoa: string, store: RefusedStore | null = refusedStoreOrNull()): void {
	try {
		store?.setItem(REFUSED_PREFIX + eoa.toLowerCase(), '')
	} catch {
		/* nothing to clear if the store is not available */
	}
}
/** The user's explicit retry after a refusal (clear paths (3)). */
export function retryFirstOpenAfterRefusal(eoa: string, store: RefusedStore | null = refusedStoreOrNull()): void {
	clearFirstOpenRefused(eoa, store)
}
