import type { PgpClassification } from './pgpRestore'
import type { RecipientLookup } from './recipientRecord'

/**
 * The chain answers, each in three states. `absent` and `unknown` are never the same: only a read that succeeded and gave a definite empty
 * answer is `absent`. A failed request, a timeout, a partial result, a record whose armor cannot be read, or an unreachable backup is
 * `unknown`, and an unknown never enters the automatic flow (constraint 1; Android constraint: exists=true with an unparseable key is
 * unknown, not absent).
 */
export type ChainPgpRead = 'record' | 'absent' | 'unknown'
export type ChainBackupRead = 'present' | 'absent' | 'unknown'

/**
 * The inputs. `restore` is the existing restore judgement (pgpRestore.classifyOwnPgp): the first open enters only on `new_account` (the
 * judgement confirms a first identity). A restore failure or a read error returns before anything else.
 */
export type AutoFirstOpenInput = {
	restore: PgpClassification
	chain: ChainPgpRead
	chainBackup: ChainBackupRead
	/** A PGP identity of this device that the automatic flow did not create (the chat key from a restore or an earlier session). */
	localOldIdentity: boolean
	/** A key this flow generated and has not registered: kept in its own store, never judged as an old identity (constraint 2). */
	localPendingOwn: boolean
}

const PUB_BEGIN = '-----BEGIN PGP PUBLIC KEY BLOCK-----'
const PUB_END = '-----END PGP PUBLIC KEY BLOCK-----'
/** Structural check of an armored public key (a decoded record that is not an armor is not a record). */
export function wellFormedPublicArmor(armor: string): boolean {
	const b = armor.indexOf(PUB_BEGIN)
	const e = armor.indexOf(PUB_END)
	return b >= 0 && e > b
}

/**
 * The chain record in three states from the AddressPGP lookup. ok with both armors well formed is a record; ok with a malformed or incomplete
 * record is unknown (exists but unreadable is not "no record"); no_record is absent; any failure is unknown.
 */
export function chainReadFromLookup(lookup: RecipientLookup): ChainPgpRead {
	if (lookup.status === 'no_record') return 'absent'
	if (lookup.status !== 'ok') return 'unknown'
	return wellFormedPublicArmor(lookup.publicArmored) && wellFormedPublicArmor(lookup.routersArmoreds) ? 'record' : 'unknown'
}

/** The encrypted backup in three states from the private blob read: missing is absent; ok or undecryptable is present; anything else unknown. */
export function chainBackupFromRead(blob: string): ChainBackupRead {
	if (blob === 'missing') return 'absent'
	if (blob === 'ok' || blob === 'undecryptable') return 'present'
	return 'unknown'
}

/**
 * The decision table. Pure. The first matching row wins. The restore judgement comes first: a failure keeps the protection, a read error
 * waits, a record that restores is the original path. Only a confirmed first identity reaches the chain answers.
 */
export function autoFirstOpenDecision(i: AutoFirstOpenInput): AutoFirstOpenDecision {
	if (i.restore.kind === 'failure') return 'keep_protection'
	if (i.restore.kind === 'read_error') return 'wait_unknown'
	// a restorable record whose armor cannot be read is unknown: it waits, it is not taken as the original path
	if (i.restore.kind === 'ok') return i.chain === 'unknown' ? 'wait_unknown' : 'use_record'
	// new_account: the chain answers must agree
	if (i.chain === 'unknown') return 'wait_unknown'
	if (i.chain === 'record') return 'use_record'
	if (i.chainBackup === 'unknown') return 'wait_unknown'
	if (i.chainBackup === 'present' || i.localOldIdentity) return 'keep_protection'
	if (i.localPendingOwn) return 'resume_pending'
	return 'generate_and_register'
}

export type AutoFirstOpenDecision = 'use_record' | 'wait_unknown' | 'keep_protection' | 'resume_pending' | 'generate_and_register'

/**
 * The local identity state, from two separate places: the chat key (chatManager.pgpKey) and the pending key of the automatic flow
 * (profile.pendingChatFirstOpen). A pending key is never an old identity: a restart continues it (constraint 2).
 */
export function classifyLocalIdentity(input: { chatKeyComplete: boolean; chatKeyAutoGenerated: boolean; pendingKeyPresent: boolean }): {
	localOldIdentity: boolean
	localPendingOwn: boolean
} {
	return {
		localOldIdentity: input.chatKeyComplete && !input.chatKeyAutoGenerated && !input.pendingKeyPresent,
		localPendingOwn: input.pendingKeyPresent || (input.chatKeyComplete && input.chatKeyAutoGenerated),
	}
}

type LockRequest = (name: string, options: { ifAvailable: boolean }, cb: (lock: unknown) => Promise<unknown>) => Promise<unknown>
export type LockManagerLike = { request: LockRequest }

const inProcess = new Set<string>()

/**
 * Runs `fn` only if no other first open of the same wallet is in flight: in any tab (Web Locks, ifAvailable), else in this process.
 * Returns 'busy' when another attempt holds the wallet.
 */
export function withFirstOpenLock<T>(
	eoa: string,
	fn: () => Promise<T>,
	locks: LockManagerLike | undefined = (globalThis as { navigator?: { locks?: LockManagerLike } }).navigator?.locks,
): Promise<T | 'busy'> {
	const name = `beamio-first-open:${eoa.toLowerCase()}`
	if (locks && typeof locks.request === 'function') {
		return locks.request(name, { ifAvailable: true }, async (lock) => (lock ? fn() : 'busy')) as Promise<T | 'busy'>
	}
	if (inProcess.has(name)) return Promise.resolve('busy')
	inProcess.add(name)
	return fn().finally(() => inProcess.delete(name))
}

export type AutoFirstOpenDeps = {
	readInputs: () => Promise<AutoFirstOpenInput>
	readChain: () => Promise<ChainPgpRead>
	registerWaitMs: () => number
	/** Generates the key and saves it locally (encrypted) before anything is sent. Resolves true only when it is saved. */
	generateAndPersist: () => Promise<boolean>
	/** Sends the registration. Resolves true only for a confirmed registration. A refusal (including 4xx) is false. */
	register: () => Promise<boolean>
	recordRegister: (ok: boolean) => void
}

export type AutoFirstOpenOutcome =
	| 'use_record'
	| 'wait_unknown'
	| 'keep_protection'
	| 'backoff'
	| 'persist_failed'
	| 'registered'
	| 'register_failed'

/**
 * One run: read the decision inputs, check the backoff, persist a new key if one is to be generated, read the chain again, then send the
 * registration once. A record that appears in between stops the run.
 */
export async function runAutoFirstOpen(deps: AutoFirstOpenDeps): Promise<AutoFirstOpenOutcome> {
	const inputs = await deps.readInputs()
	const decision = autoFirstOpenDecision(inputs)
	if (decision === 'use_record') return 'use_record'
	if (decision === 'wait_unknown') return 'wait_unknown'
	if (decision === 'keep_protection') return 'keep_protection'
	if (deps.registerWaitMs() > 0) return 'backoff'
	if (decision === 'generate_and_register') {
		if (!(await deps.generateAndPersist())) return 'persist_failed'
	}
	// the chain is read again before anything is sent: a record that appeared in the meantime stops this run
	const again = await deps.readChain()
	if (again === 'record') return 'use_record'
	if (again === 'unknown') return 'wait_unknown'
	const ok = await deps.register()
	deps.recordRegister(ok)
	return ok ? 'registered' : 'register_failed'
}
